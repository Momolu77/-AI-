"""Generate Zod schemas and payload types from the shared event registry."""

import argparse
import json

from common import ROOT


def zod(spec):
    if isinstance(spec, str):
        primitives = {
            "str": "z.string()",
            "time": "z.iso.datetime({ offset: true })",
            "id": "z.string().regex(/^[A-Za-z0-9_-]{1,80}$/)",
            "nat": "z.number().int().nonnegative()",
            "positive": "z.number().int().positive()",
            "number": "z.number()",
            "nonnegative": "z.number().nonnegative()",
            "bool": "z.boolean()",
        }
        return primitives.get(spec, spec + "Schema")
    if "nullable" in spec:
        return zod(spec["nullable"]) + ".nullable()"
    if "array" in spec:
        return "z.array(" + zod(spec["array"]) + ")"
    if "enum" in spec:
        return "z.enum(" + json.dumps(spec["enum"]) + ")"
    if "union" in spec:
        return "z.union([" + ",".join(zod(v) for v in spec["union"]) + "])"
    return (
        "z.strictObject({"
        + ",".join(json.dumps(k) + ":" + zod(v) for k, v in spec["object"].items())
        + "})"
    )


def generate():
    contract = json.loads((ROOT / "config/events-v1.3.json").read_text(encoding="utf-8"))
    lines = [
        "// Generated by scripts/generate_event_contract.py; edit config/events-v1.3.json.",
        "import { z } from 'zod'",
    ]
    for name, definition in contract["definitions"].items():
        lines.append(f"const {name}Schema = {zod(definition)}")
    lines.append(
        "export const schemaVersion = " + json.dumps(contract["schema_version"]) + " as const"
    )
    lines.append("export const eventSchemas = {")
    for name, event in contract["events"].items():
        lines.append(json.dumps(name) + ": " + zod({"object": event["fields"]}) + ",")
    lines += [
        "}",
        "export type EventName = keyof typeof eventSchemas",
        "export type EventPayloads = { [K in EventName]: z.infer<(typeof eventSchemas)[K]> }",
    ]
    lines.append(
        "export const eventActors = "
        + json.dumps({n: e["actor"] for n, e in contract["events"].items()})
        + " as const"
    )
    lines.append(
        "export const eventOwners = "
        + json.dumps({n: e["owner"] for n, e in contract["events"].items()})
        + " as const"
    )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "frontend/src/generated/event-contract.ts"
    content = generate()
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit("Generated contract is stale")
    else:
        path.parent.mkdir(exist_ok=True)
        path.write_text(content, encoding="utf-8")
